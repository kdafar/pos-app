// Writes src/main/receiptFont.generated.ts: Open Sans (latin), as base64, for
// print.ts to embed in every printed page. Re-run only to change the font:
//   node scripts/embed-receipt-font.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'node_modules/@fontsource/open-sans/files');
const weights = [400, 600, 700];

const entries = weights.map((w) => {
  const file = path.join(dir, `open-sans-latin-${w}-normal.woff2`);
  return `  ${w}: '${fs.readFileSync(file).toString('base64')}',`;
});

const out = `// GENERATED by scripts/embed-receipt-font.mjs — do not edit.
// Open Sans, latin subset, woff2. SIL Open Font License 1.1.
export const RECEIPT_FONT_WOFF2: Record<number, string> = {
${entries.join('\n')}
};
`;

fs.writeFileSync(path.join(root, 'src/main/receiptFont.generated.ts'), out);
console.log('wrote src/main/receiptFont.generated.ts');
